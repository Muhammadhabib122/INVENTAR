export type LangCode = 'LAT' | 'CYR';

export function translate(lang: LangCode, key: MsgKey, vars?: Record<string, string | number>) {
  let s: string = (lang === 'CYR' ? cyr[key] : undefined) ?? lat[key] ?? String(key);
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}
